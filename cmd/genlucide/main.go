// Command genlucide generates Go icon variables from the lucide-react package.
//
//	go run ./cmd/genlucide -src path/to/node_modules/lucide-react -names icons/lucide/names.txt -out icons/lucide/lucide_gen.go
//
// names.txt lists the icons to include as lucide-react component names
// (FolderOpen, LoaderCircle, ...), one per line. Aliases are resolved.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	nameRe    = regexp.MustCompile(`name:\s*"([^"]+)"`)
	aliasesRe = regexp.MustCompile(`aliases:\s*\[([^\]]*)\]`)
	nodeRe    = regexp.MustCompile(`\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]`)
	attrRe    = regexp.MustCompile(`"?([\w-]+)"?\s*:\s*"([^"]*)"`)
	strRe     = regexp.MustCompile(`"([^"]+)"`)
	versionRe = regexp.MustCompile(`"version":\s*"([^"]+)"`)
)

type icon struct {
	name string
	body string
}

func pascal(kebab string) string {
	var b strings.Builder
	for _, part := range strings.Split(kebab, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func main() {
	src := flag.String("src", "", "lucide-react package directory")
	namesPath := flag.String("names", "icons/lucide/names.txt", "file listing icon names")
	out := flag.String("out", "icons/lucide/lucide_gen.go", "output Go file")
	flag.Parse()
	if *src == "" {
		log.Fatal("-src is required")
	}

	pkg, err := os.ReadFile(filepath.Join(*src, "package.json"))
	if err != nil {
		log.Fatal(err)
	}
	lic, err := os.ReadFile(filepath.Join(*src, "LICENSE"))
	if err != nil {
		log.Fatalf("genlucide: reading the lucide-react LICENSE: %v", err)
	}
	version := "unknown"
	if m := versionRe.FindSubmatch(pkg); m != nil {
		version = string(m[1])
	}

	files, err := filepath.Glob(filepath.Join(*src, "dist", "esm", "icons", "*.mjs"))
	if err != nil {
		log.Fatal(err)
	}
	byName := map[string]icon{}
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		s := string(data)
		m := nameRe.FindStringSubmatch(s)
		if m == nil {
			continue
		}
		var body strings.Builder
		for _, n := range nodeRe.FindAllStringSubmatch(s, -1) {
			fmt.Fprintf(&body, "<%s", n[1])
			for _, a := range attrRe.FindAllStringSubmatch(n[2], -1) {
				if a[1] == "key" {
					continue
				}
				fmt.Fprintf(&body, ` %s="%s"`, a[1], a[2])
			}
			body.WriteString("/>")
		}
		ic := icon{name: m[1], body: body.String()}
		byName[pascal(m[1])] = ic
		if am := aliasesRe.FindStringSubmatch(s); am != nil {
			for _, a := range strRe.FindAllStringSubmatch(am[1], -1) {
				if _, taken := byName[pascal(a[1])]; !taken {
					byName[pascal(a[1])] = ic
				}
			}
		}
	}

	nf, err := os.Open(*namesPath)
	if err != nil {
		log.Fatal(err)
	}
	defer nf.Close()
	var names []string
	sc := bufio.NewScanner(nf)
	for sc.Scan() {
		if n := strings.TrimSpace(sc.Text()); n != "" && !strings.HasPrefix(n, "#") {
			names = append(names, n)
		}
	}
	sort.Strings(names)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by genlucide from lucide-react %s; DO NOT EDIT.\n\n", version)
	b.WriteString("// Package lucide holds Lucide icons (ISC and MIT licenses, see LICENSE) for fairy.Icon.\n")
	b.WriteString("package lucide\n\nimport \"github.com/myparsleycat/fairy/svg\"\n\n")
	b.WriteString("const head = `<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\">`\n\n")
	b.WriteString("func icon(body string) *svg.Vector { return svg.Lazy(head + body + \"</svg>\") }\n\n")
	b.WriteString("var (\n")
	missing := 0
	for _, n := range names {
		ic, ok := byName[n]
		if !ok {
			log.Printf("genlucide: no icon named %s", n)
			missing++
			continue
		}
		fmt.Fprintf(&b, "\t%s = icon(`%s`) // %s\n", n, ic.body, ic.name)
	}
	b.WriteString(")\n")
	code, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(filepath.Dir(*out), "LICENSE"), lic, 0o644); err != nil {
		log.Fatalf("genlucide: writing LICENSE: %v", err)
	}
	log.Printf("genlucide: wrote %d icons (%d missing)", len(names)-missing, missing)
}
