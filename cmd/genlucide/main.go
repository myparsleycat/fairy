// Command genlucide generates Go icon variables for every icon in the lucide-react package.
//
//	go run ./cmd/genlucide -src path/to/node_modules/lucide-react -out icons/lucide/lucide_gen.go
//
// Each icon becomes a variable named after its lucide-react component (FolderOpen, LoaderCircle, ...).
// The aliases lucide-react keeps for renamed icons become variables with the same drawing.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"log"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var (
	nameRe    = regexp.MustCompile(`name:\s*"([^"]+)"`)
	aliasesRe = regexp.MustCompile(`aliases:\s*\[([^\]]*)\]`)
	nodeRe    = regexp.MustCompile(`\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]`)
	attrRe    = regexp.MustCompile(`"?([\w-]+)"?\s*:\s*"([^"]*)"`)
	strRe     = regexp.MustCompile(`"([^"]+)"`)
	versionRe = regexp.MustCompile(`"version":\s*"([^"]+)"`)
)

type icon struct {
	name string
	body string
}

type alias struct {
	name   string
	target string
}

func pascal(kebab string) string {
	var b strings.Builder
	for _, part := range strings.Split(kebab, "-") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func identifier(kebab string) string {
	id := pascal(kebab)
	if !token.IsIdentifier(id) || !token.IsExported(id) {
		log.Fatalf("genlucide: %s does not map to an exported Go identifier (%q)", kebab, id)
	}
	return id
}

func main() {
	src := flag.String("src", "", "lucide-react package directory")
	out := flag.String("out", "icons/lucide/lucide_gen.go", "output Go file")
	flag.Parse()
	if *src == "" {
		log.Fatal("-src is required")
	}

	pkg, err := os.ReadFile(filepath.Join(*src, "package.json"))
	if err != nil {
		log.Fatal(err)
	}
	lic, err := os.ReadFile(filepath.Join(*src, "LICENSE"))
	if err != nil {
		log.Fatalf("genlucide: reading the lucide-react LICENSE: %v", err)
	}
	version := "unknown"
	if m := versionRe.FindSubmatch(pkg); m != nil {
		version = string(m[1])
	}

	files, err := filepath.Glob(filepath.Join(*src, "dist", "esm", "icons", "*.mjs"))
	if err != nil {
		log.Fatal(err)
	}
	icons := map[string]icon{}
	var aliases []alias
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		s := string(data)
		m := nameRe.FindStringSubmatch(s)
		if m == nil {
			continue
		}
		var body strings.Builder
		for _, n := range nodeRe.FindAllStringSubmatch(s, -1) {
			fmt.Fprintf(&body, "<%s", n[1])
			for _, a := range attrRe.FindAllStringSubmatch(n[2], -1) {
				if a[1] == "key" {
					continue
				}
				fmt.Fprintf(&body, ` %s="%s"`, a[1], a[2])
			}
			body.WriteString("/>")
		}
		if body.Len() == 0 {
			log.Fatalf("genlucide: %s has no drawable nodes", f)
		}

		id := identifier(m[1])
		if prev, taken := icons[id]; taken {
			log.Fatalf("genlucide: %s and %s both map to %s", prev.name, m[1], id)
		}
		icons[id] = icon{name: m[1], body: body.String()}
		if am := aliasesRe.FindStringSubmatch(s); am != nil {
			for _, a := range strRe.FindAllStringSubmatch(am[1], -1) {
				aliases = append(aliases, alias{name: a[1], target: id})
			}
		}
	}

	// An alias never shadows an icon; among aliases that collide, the first in file order wins.
	aliasOf := map[string]alias{}
	for _, a := range aliases {
		id := identifier(a.name)
		if _, taken := icons[id]; taken {
			continue
		}
		if prev, taken := aliasOf[id]; taken {
			if prev.target != a.target {
				log.Printf("genlucide: alias %s already points to %s, not %s", id, prev.target, a.target)
			}
			continue
		}
		aliasOf[id] = a
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by genlucide from lucide-react %s; DO NOT EDIT.\n\n", version)
	b.WriteString("// Package lucide holds Lucide icons (ISC and MIT licenses, see LICENSE) for fairy.Icon.\n")
	b.WriteString("// Icons a program does not reference are left out by the linker.\n")
	b.WriteString("package lucide\n\nimport \"github.com/myparsleycat/fairy/svg\"\n\n")
	b.WriteString("const head = `<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\">`\n\n")
	b.WriteString("func icon(body string) *svg.Vector { return svg.Lazy(head + body + \"</svg>\") }\n\n")
	b.WriteString("var (\n")
	for _, id := range slices.Sorted(maps.Keys(icons)) {
		ic := icons[id]
		// A trailing comment would be padded to the longest body by gofmt.
		fmt.Fprintf(&b, "\t// %s\n\t%s = icon(`%s`)\n", ic.name, id, ic.body)
	}
	b.WriteString(")\n\n")
	// "Alias = Target" would be assigned by package init code, which keeps every
	// target linked; repeating the body keeps aliases statically initialized.
	b.WriteString("// Former names of renamed icons, kept by lucide-react as aliases.\n")
	b.WriteString("var (\n")
	for _, id := range slices.Sorted(maps.Keys(aliasOf)) {
		a := aliasOf[id]
		fmt.Fprintf(&b, "\t// %s, alias of %s\n\t%s = icon(`%s`)\n", a.name, a.target, id, icons[a.target].body)
	}
	b.WriteString(")\n")

	code, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(filepath.Dir(*out), "LICENSE"), lic, 0o644); err != nil {
		log.Fatalf("genlucide: writing LICENSE: %v", err)
	}
	log.Printf("genlucide: wrote %d icons and %d aliases from lucide-react %s", len(icons), len(aliasOf), version)
}
